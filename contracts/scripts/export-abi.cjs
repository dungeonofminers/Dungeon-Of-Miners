// 1. Writes the compiled DomStaking ABI to ../src/lib/stakingAbi.ts for the website (wagmi/viem).
// 2. Writes contracts/DomStaking.standard-input.json from the exact build-info referenced by DomStaking.dbg.json.
// Run after `npm run compile`.
const fs = require("fs");
const path = require("path");

const artifactDir = path.join(__dirname, "..", "artifacts", "contracts", "DomStaking.sol");
const artifact = JSON.parse(fs.readFileSync(path.join(artifactDir, "DomStaking.json"), "utf8"));
const dbg = JSON.parse(fs.readFileSync(path.join(artifactDir, "DomStaking.dbg.json"), "utf8"));

const out = path.join(__dirname, "..", "..", "src", "lib", "stakingAbi.ts");
const body =
  "// AUTO-GENERATED by contracts/scripts/export-abi.cjs — do not edit by hand.\n" +
  `export const domStakingAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
fs.writeFileSync(out, body);
console.log(`wrote ${path.relative(process.cwd(), out)} (${artifact.abi.length} entries)`);

const buildInfoPath = path.resolve(artifactDir, dbg.buildInfo);
const bi = JSON.parse(fs.readFileSync(buildInfoPath, "utf8"));
const sources = {};
for (const [k, v] of Object.entries(bi.input.sources)) {
  if (k.startsWith("contracts/test/")) continue;
  sources[k] = v;
}
const stdInput = {
  language: bi.input.language,
  sources,
  settings: bi.input.settings,
};
const stdOut = path.join(__dirname, "..", "DomStaking.standard-input.json");
fs.writeFileSync(stdOut, JSON.stringify(stdInput, null, 2));
console.log(
  `wrote ${path.relative(process.cwd(), stdOut)} (${Object.keys(sources).length} source files, solc v${bi.solcLongVersion})`
);
